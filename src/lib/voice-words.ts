/** 「承る」「承ります」「承っております」（「承知」はそのまま） */
const UKETAMAWARU = /承(?=[りるっれろらわ])/g;

/** 畳の「縁」（縁代・縁別・縁の値段・石田縁 など）は「へり」。縁側・縁起・ご縁 などは畳の縁ではないのでそのまま */
