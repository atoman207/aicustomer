// ご依頼済みの件（すでに決まっている工事・納品・お見積りの訪問）の日程変更・キャンセル・仕様変更のお問い合わせ
//   一畳屋様の「Ai system」236 行目「日程変更などの問い合わせについて：すでに工事が決まっていて日程変更やキャンセルや仕様変更の
//   問い合わせがくる（特に電話の場合）その時は改めて担当者から折り返す旨を伝える。そのときも再度 名前・電話番号・住所・問い合わせ
//   内容を聞く ※無料見積の案内はしない」（修正点など 12 行目のご指摘 2026-11-12「236行目のルールが反映されず、名前等を聞いてこない」）
//   それまでは、AI が「担当者より折り返します」と答えるだけで、お名前などを伺わず、受付一覧にも入らなかった（折り返す先がわからない）。
//   → 文字・声・電話・LINE で、折り返しの旨を伝えてから お名前 → お電話番号 → ご住所 → お問い合わせの内容 を伺い、確認画面（電話は復唱）
//     から受付一覧へ。訪問のご希望日は伺わず「（折り返しの際にご相談）」、相談内容の頭に「【ご依頼済みの件の変更・キャンセル】」。
// ブラウザ（offer.ts・確認画面）とサーバーの両方で使うので、ほかのモジュールを読み込まない

export type JobChangeKind = "schedule" | "cancel" | "spec";

/** 受付一覧の相談内容の頭に付ける印（担当者が新しいお見積りのご依頼と見分けられるように） */
export const JOB_CHANGE_TAG = "【ご依頼済みの件の変更・キャンセル】";
/** 訪問のご希望日の欄（伺わない。電話の折り返しの受付と同じ書き方） */
export const JOB_CHANGE_DATES = "（折り返しの際にご相談）";

/** すでに決まっている・ご依頼済みのこと（「先日お願いした」「注文した」「納品」「工事日」「来てもらう予定」など） */
const EXISTING =
  /先日|以前|前回|この前|こないだ|この間|先週|先月|依頼済|依頼(?:して|した|中)|頼んで|頼んだ|注文(?:した|して|済|中|の|分)|発注|契約(?:した|して|済|中)|予約(?:した|して|済|中|の)|お願いして(?:い|お|る|た)|お願いした|お願い済|お願い中|決まって|決定して|確定して|予定(?:の|して|され|が|に|で|は|を|です|だった)|工事日|施工日|作業日|納品|引き?取り|取り?付け(?:日|の日)|訪問日|伺う日|来ていただく日|来てもらう|来ていただく|来てくれる|来られる|(?:見積|みつもり)(?:り|もり)?(?:日|の日|の訪問|に来)/;

/** キャンセル（取りやめ） */
const CANCEL = /キャンセル|取り消|取消|中止|取りやめ|とりやめ|やめ(?:たい|にしたい|させて|ます|ること)|なしにしたい|断りたい|お断りしたい/;
/**
 * キャンセルそのもののお願い（「キャンセルしたい」は、ご依頼済みのことを言わなくても、決まっているものの取りやめ）。
 * 「見積のあとキャンセルできますか？」のような、これからのご依頼の質問は含めない
 */
const CANCEL_REQUEST = /キャンセル(?:したい|します|させて|を(?:お願い|したい)|お願い|でお願い)|取り消(?:したい|して(?:ほしい|ください|もらえ|いただ))|中止(?:したい|して(?:ほしい|ください|もらえ|いただ))/;
/** 日程・時間の変更 */
const SCHEDULE =
  /(?:日程|日にち|日時|日付|予定|時間|時刻|曜日|納期|工事|施工|作業|納品|訪問|引き?取り|取り?付け|来ていただく日|伺う日|見積(?:り|もり)?の日)[^。？?！!\n]{0,14}(?:変更|変え|かえ|替え|ずら|延期|延ば|のば|早め|遅ら|おそら|前倒し|後ろ倒し|調整|別の日|違う日|ほかの日|他の日)|(?:別の日|違う日|ほかの日|他の日)に(?:して|変え|でき|お願い)|延期|日程の?変更|リスケ/;
/** ご依頼の内容（仕様）の変更 */
const SPEC =
  /(?:色|柄|ヘリ|へり|縁|種類|グレード|品番|商品|材料|素材|仕様|内容|枚数|数量|サイズ|デザイン|生地|表|ござ|和紙|網|紙)[^。？?！!\n]{0,12}(?:変更|変え|かえ|替え(?:たい|て|られ)|追加|減ら|増や|取り替え|取りかえ)|仕様の?変更|追加で(?:お願い|依頼)/;

/**
 * ご依頼済みの件の変更・キャンセルのお問い合わせか（どれでもなければ null）。
 * 日程・仕様の変更は、ご依頼済み・決まっていることがわかる言葉があるときだけ（「ヘリの色は変えられますか？」のような、これからのご依頼の質問は除く）。
 * キャンセルは「キャンセルしたい」とはっきりおっしゃったときも
 */
export function jobChangeKind(text: string): JobChangeKind | null {
  const s = text.normalize("NFKC").replace(/\s+/g, "");
  if (!s) return null;
  const existing = EXISTING.test(s);
  if (CANCEL.test(s) && (existing || CANCEL_REQUEST.test(s))) return "cancel";
  if (SCHEDULE.test(s) && (existing || SCHEDULE_REQUEST.test(s))) return "schedule";
  if (SPEC.test(s) && existing) return "spec";
  return null;
}

/** 日程の変更そのもののお願い（「日程を変更したい」「延期してほしい」。決まっている予定があるときの言い方） */
const SCHEDULE_REQUEST =
  /(?:日程|日にち|日時|予定)(?:を|の)?(?:変更(?:したい|して(?:ほしい|ください|もらえ|いただ)|をお願い)|変えたい|変えて(?:ほしい|ください|もらえ|いただ)|ずらしたい|ずらして(?:ほしい|ください|もらえ|いただ))|延期(?:したい|して(?:ほしい|ください|もらえ|いただ)|をお願い)|リスケ/;

/** 会話（お客様の発言）がご依頼済みの件の変更・キャンセルのお問い合わせか（いちばん最近のものを返す） */
export function jobChangeInTalk(messages: { role: string; content: string }[]): JobChangeKind | null {
  for (let i = messages.length - 1; i >= 0; i--) {
    const m = messages[i];
    if (m.role !== "user") continue;
    const k = jobChangeKind(m.content);
    if (k) return k;
  }
  return null;
}

/** 受付の相談内容が、ご依頼済みの件の変更・キャンセルのもの（確認画面の文・控え・受付一覧で見分ける。電話の受付は頭に【要確認…】が付く） */
export function isJobChangeSummary(summary: string | undefined | null): boolean {
  return Boolean(summary && summary.includes(JOB_CHANGE_TAG));
}

/** 相談内容の頭に印を付ける（もう付いていればそのまま） */
export function tagJobChange(summary: string | undefined | null): string {
  const s = (summary ?? "").trim();
  if (!s) return JOB_CHANGE_TAG.replace(/】$/, "のお問い合わせ】");
  return isJobChangeSummary(s) ? s : `${JOB_CHANGE_TAG}${s}`;
}

const KIND_LABEL: Record<JobChangeKind, string> = {
  schedule: "日程の変更",
  cancel: "キャンセル",
  spec: "内容の変更",
};

/** 最初の返事：折り返しの旨を伝える（このあとに「確認のため、お名前を…」を続ける。無料見積の案内はしない） */
export function jobChangeOpening(kind: JobChangeKind): string {
  return `ご依頼いただいている件の${KIND_LABEL[kind]}のご連絡ですね。ありがとうございます。改めて担当者より折り返しご連絡いたします。`;
}

/** 伺う順（236 行目のとおり：お名前 → お電話番号 → ご住所） */
export const JOB_CHANGE_ORDER = ["name", "phone", "address"] as const;

/** お問い合わせの内容を伺う文（日程の変更：変更後のご希望／内容の変更：どのように）。キャンセルは伺わない */
export function jobChangeDetailAsk(kind: JobChangeKind): string | null {
  if (kind === "schedule") return "最後に、変更をご希望の日時はございますか？（未定でしたら「未定」で結構です）";
  if (kind === "spec") return "最後に、どのように変更をご希望か、わかる範囲で教えていただけますか？";
  return null;
}

/** お問い合わせの内容がもう伺えているか（日程：日付・時間の言葉がある／内容：何にするかがある） */
export function jobChangeDetailGiven(kind: JobChangeKind, userTexts: string[]): boolean {
  if (kind === "cancel") return true;
  const s = userTexts.join("\n").normalize("NFKC");
  if (kind === "schedule") return /\d{1,2}\s*(?:月|日|時)|午前|午後|朝|夕方|来週|再来週|今週|来月|月末|月初|平日|土日|週末|曜|未定|いつでも|おまかせ|お任せ/.test(s);
  // 内容の変更：何にするか（「茶色にしたい」）、またはご事情まで詳しく書かれている（「…引き取りに来た際に、見本を見て決めたい」）
  return /[^。？?\n]{1,20}(?:に|へ)(?:変更|変え|かえ|替え|して|したい)|(?:がいい|が良い|にしたい|にしてほしい|でお願い)/.test(s) || s.replace(/\s+/g, "").length >= 30;
}

